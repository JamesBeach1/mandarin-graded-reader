// Build reverse Traditional -> Simplified map
export const T2S_MAP: Record<string, string> = {};
for (const [simp, trad] of Object.entries(S2T_MAP)) {
  if (simp !== trad && !T2S_MAP[trad]) {
    T2S_MAP[trad] = simp;
  }
}

/**
 * Converts a Chinese string to Traditional glyphs.
 */
export function toTraditional(text: string): string {
  if (!text) return '';
  let result = '';
  for (const char of text) {
    result += S2T_MAP[char] || char;
  }
  return result;
}

/**
 * Converts a Chinese string to Simplified glyphs.
 */
export function toSimplified(text: string): string {
  if (!text) return '';
  let result = '';
  for (const char of text) {
    result += T2S_MAP[char] || char;
  }
  return result;
}

/**
 * Converts a string to the desired Chinese script.
 */
export function convertScript(text: string, script: ChineseScript): string {
  if (script === 'traditional') {
    return toTraditional(text);
  }
  return toSimplified(text);
}

/**
 * Checks if a character has a distinct traditional form.
 */
export function hasTraditionalVariant(char: string): boolean {
  return Boolean(S2T_MAP[char] && S2T_MAP[char] !== char);
}

/**
 * Returns traditional variant if one exists and differs, else null.
 */
export function getTraditionalVariant(char: string): string | null {
  const trad = S2T_MAP[char];
  return trad && trad !== char ? trad : null;
}
